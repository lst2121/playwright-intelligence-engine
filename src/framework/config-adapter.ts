import fs from 'node:fs/promises';
import path from 'node:path';
import { Project, SyntaxKind, ObjectLiteralExpression } from 'ts-morph';

export interface PlaywrightConfigSummary {
  configPath: string;
  testDir: string;
  timeoutMs: number;
  retries: number;
  workers?: number | string;
  traceSetting: 'off' | 'on' | 'retain-on-failure' | 'on-first-retry' | 'unknown';
  projects: Array<{ name: string; use?: Record<string, any> }>;
}

export class ConfigAdapter {
  private static readonly CONFIG_NAMES = [
    'playwright.config.ts',
    'playwright.config.js',
    'playwright.config.mjs',
    'playwright.config.cjs',
  ];

  /**
   * Finds and summarizes the Playwright config in a repository.
   */
  public static async findConfig(repoDir: string): Promise<PlaywrightConfigSummary | null> {
    for (const name of ConfigAdapter.CONFIG_NAMES) {
      const fullPath = path.resolve(repoDir, name);
      try {
        await fs.access(fullPath);
        return ConfigAdapter.parseConfig(fullPath);
      } catch {
        continue;
      }
    }
    return null;
  }

  /**
   * Statically parses a playwright.config.ts file via ts-morph AST without evaluating untrusted code.
   */
  public static parseConfig(configPath: string): PlaywrightConfigSummary {
    const project = new Project({ skipAddingFilesFromTsConfig: true });
    const sourceFile = project.addSourceFileAtPath(configPath);

    let testDir = './tests';
    let timeoutMs = 30000;
    let retries = 0;
    let traceSetting: PlaywrightConfigSummary['traceSetting'] = 'unknown';
    const projects: PlaywrightConfigSummary['projects'] = [];

    // Look for defineProperty or export default defineConfig({...})
    sourceFile.forEachDescendant((node) => {
      if (node.isKind(SyntaxKind.ObjectLiteralExpression)) {
        const obj = node as ObjectLiteralExpression;

        const testDirProp = obj.getProperty('testDir');
        if (testDirProp && 'getInitializer' in testDirProp) {
          const init = (testDirProp as any).getInitializer();
          if (init) testDir = init.getText().replace(/['"]/g, '');
        }

        const timeoutProp = obj.getProperty('timeout');
        if (timeoutProp && 'getInitializer' in timeoutProp) {
          const init = (timeoutProp as any).getInitializer();
          if (init && !isNaN(Number(init.getText()))) {
            timeoutMs = Number(init.getText());
          }
        }

        const retriesProp = obj.getProperty('retries');
        if (retriesProp && 'getInitializer' in retriesProp) {
          const init = (retriesProp as any).getInitializer();
          if (init && !isNaN(Number(init.getText()))) {
            retries = Number(init.getText());
          }
        }

        // Check use.trace
        const useProp = obj.getProperty('use');
        if (useProp && 'getInitializer' in useProp) {
          const useInit = (useProp as any).getInitializer();
          if (useInit && useInit.isKind(SyntaxKind.ObjectLiteralExpression)) {
            const traceProp = (useInit as ObjectLiteralExpression).getProperty('trace');
            if (traceProp && 'getInitializer' in traceProp) {
              const traceInit = (traceProp as any).getInitializer();
              const val = traceInit?.getText().replace(/['"]/g, '');
              if (['off', 'on', 'retain-on-failure', 'on-first-retry'].includes(val)) {
                traceSetting = val as any;
              }
            }
          }
        }
      }
    });

    return {
      configPath,
      testDir,
      timeoutMs,
      retries,
      traceSetting,
      projects,
    };
  }

  /**
   * Generates a temporary verification config string with retries disabled and tracing enabled.
   */
  public static generateVerificationOverride(baseConfigPath?: string): string {
    const importStatement = baseConfigPath
      ? `import baseConfig from './${path.basename(baseConfigPath).replace(/\.ts$/, '')}';\n`
      : `import { defineConfig } from '@playwright/test';\n`;

    return `${importStatement}
// Auto-generated by Playwright Intelligence Engine for isolated worktree verification
export default {
  ...(typeof baseConfig !== 'undefined' ? baseConfig : {}),
  retries: 0, // Deterministic: retries disabled to measure true flakiness
  workers: 1, // Deterministic single-worker isolation
  use: {
    ...(typeof baseConfig !== 'undefined' && baseConfig.use ? baseConfig.use : {}),
    trace: 'retain-on-failure',
    video: 'off',
    screenshot: 'only-on-failure',
  },
};
`;
  }
}

